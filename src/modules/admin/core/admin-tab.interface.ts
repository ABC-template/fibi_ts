export interface IAdminTab {
  /** Уникальный id вкладки */
  id: string;

  /** Название во вкладках */
  label: string;

  /** Иконка (эмодзи) */
  icon: string;

  /** Порядок сортировки (меньше = левее) */
  priority: number;

  /** Инициализация (загрузка данных) */
  init(): Promise<void>;

  /** Рендер HTML содержимого */
  render(): string;

  /** Вызывается при показе вкладки */
  onShow?(): void;

  /** Вызывается при скрытии вкладки */
  onHide?(): void;

  /** Принудительное обновление данных */
  refresh?(): Promise<void>;

  /** Очистка */
  destroy(): void;
}
